const SENSITIVE_PARTS = [
  'api_key', 'apikey', 'token', 'cookie', 'authorization', 'password', 'secret',
  'request_header', 'response_header', 'system_prompt', 'developer_prompt',
  'traceback', 'stack_trace', 'filesystem_path', 'file_path', 'environment',
]

export function businessFieldLabel(key: string): string {
  const normalized = key.trim()
  if (!normalized) return '未命名字段'
  if (FIELD_LABELS[normalized]) return FIELD_LABELS[normalized]
  if (Array.from(normalized).some((character) => (character.codePointAt(0) || 0) > 127)) return normalized
  const suffix = normalized.endsWith('_pct') ? '（%）' : ''
  const words = normalized
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase()
    .replace(/_pct$/, '')
    .split(/[_\s.-]+/)
    .filter(Boolean)
  const translated = words.map((word) => ({ api: 'API', id: '编号', nav: '净值', ...FIELD_WORDS })[word] || '').filter(Boolean)
  return translated.length ? `${translated.join('')}${suffix}` : '扩展业务指标'
}

export function businessValueLabel(value: string): string {
  return VALUE_LABELS[value] || value
}

export function isSensitiveBusinessKey(key: string): boolean {
  const normalized = key.trim().toLowerCase()
  return SENSITIVE_PARTS.some((part) => normalized.includes(part))
}

